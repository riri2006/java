public class switchcase{
    public static void main(String[] args){
        int place = 2;
        switch(place){
            case 1:
                System.out.println("1 is Meghalaya");
                break;
            case 2:
                System.out.println("2 is Sikkim");
                break; 
            case 3:
                System.out.println("3 is Nainital");
                break;
            default:
                System.out.println("Invalid place");
                break;
        }
        
        
    }
}